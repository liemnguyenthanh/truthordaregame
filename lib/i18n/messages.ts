/** Keep server validation useful while avoiding Vietnamese error text in English UI. */
export function localizedError(locale: 'vi' | 'en', message: string): string {
  if (locale === 'vi') return message;
  return (
    englishMessages[message] ??
    (/[À-ỹĐđ]/.test(message)
      ? 'Something went wrong. Please check your details and try again.'
      : message)
  );
}
